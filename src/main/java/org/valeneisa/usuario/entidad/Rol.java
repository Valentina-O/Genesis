package org.valeneisa.usuario.entidad;

/**
 * Enumeración que define los roles disponibles en el sistema.
 * Se utiliza para controlar el acceso y permisos de los usuarios.
 */
public enum Rol {

    /**
     * Rol con privilegios administrativos.
     */
    ADMIN,

    /**
     * Rol estándar para usuarios del sistema.
     */
    USER
}